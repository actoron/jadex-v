def write_classpath_file(
    pkg_dir,
    src_dirs,
    internal_deps,
    maven_deps,
    maven_jars,
    jdk,
):
    """
    Write Eclipse .classpath.

    All classpath entries are collected first and deduplicated by their
    effective Eclipse classpath identity before being written.
    """

    # Key -> XML entry
    # The key is deliberately independent of the Maven/Bazel label.
    entries = {}

    def add_entry(key, xml):
        entries[key] = xml

    # Source directories
    for src in src_dirs:
        add_entry(
            ("src", src),
            f'\t<classpathentry kind="src" path="{src}"/>',
        )

    # JRE
    jre_path = (
        f"org.eclipse.jdt.launching.JRE_CONTAINER/"
        f"org.eclipse.jdt.internal.debug.ui.launcher."
        f"StandardVMType/JavaSE-{jdk}"
    )

    add_entry(
        ("con", jre_path),
        f'\t<classpathentry kind="con" path="{jre_path}"/>',
    )

    # Internal Eclipse project dependencies
    for dep_pkg in internal_deps:
        project_name = project_name_for_package(dep_pkg)
        path = f"/{project_name}"

        add_entry(
            ("project", path),
            f'\t<classpathentry combineaccessrules="false" '
            f'kind="src" path="{path}"/>',
        )

    missing = []

    # Maven dependencies
    for label in sorted(maven_deps):
        info = maven_jars.get(label)

        if not info:
            missing.append(label)
            continue

        # Normalize the actual physical JAR path.
        jar_path = os.path.normcase(
            os.path.normpath(info["jar"])
        )

        src_path = info.get("srcjar")
        if src_path:
            src_path = os.path.normcase(
                os.path.normpath(src_path)
            )

        # IMPORTANT:
        # Deduplicate by the actual JAR path, NOT by the Maven label.
        #
        # Thus:
        #
        #   @maven//:foo
        #   @maven//:foo_duplicate
        #
        # are still only one Eclipse classpath entry if both resolve
        # to the same physical JAR.
        add_entry(
            ("lib", jar_path),
            (
                f'\t<classpathentry kind="lib" '
                f'path="{jar_path}"'
                f'{f" sourcepath=\"{src_path}\"" if src_path else ""}/>'
            ),
        )

    # Output directory
    add_entry(
        ("output", "bin"),
        '\t<classpathentry kind="output" path="bin"/>',
    )

    # Write deterministic output.
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<classpath>",
        f"\t<!-- {AUTO_GEN_NOTICE} -->",
    ]

    for key in sorted(entries, key=str):
        lines.append(entries[key])

    lines.append("</classpath>")

    content = "\n".join(lines) + "\n"

    with open(os.path.join(pkg_dir, ".classpath"), "w") as f:
        f.write(content)

    return missing


