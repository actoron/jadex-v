def find_project_dirs(workspace):
    """Depth-first scan of the *entire* tree for every folder containing a
    .project file -- regardless of whether this script generated it. This
    catches leftover project files from earlier plugin attempts that Bazel
    itself doesn't know about (bazel query only sees Bazel packages)."""
    found = []
    for dirpath, dirnames, filenames in os.walk(workspace):
        # skip bazel's own convenience symlinks / vcs dirs -- huge and irrelevant
        dirnames[:] = [
            d for d in dirnames
            if not d.startswith("bazel-") and d not in (".git", "bazel-out")
        ]
        if ".project" in filenames:
            found.append(dirpath)
    return found


def prune_nested_projects(workspace):
    """Keep only the deepest project in any ancestor/descendant chain --
    Eclipse doesn't support nested projects. Auto-removes our own
    AUTO-GENERATED ancestor files; warns (without touching) about foreign
    ones so nothing unrelated gets silently deleted."""
    proj_dirs = sorted(find_project_dirs(workspace), key=len)
    proj_set = set(proj_dirs)
    removed, foreign_conflicts = [], []

    for d in proj_dirs:
        prefix = d + os.sep
        is_ancestor = any(other != d and other.startswith(prefix) for other in proj_set)
        if not is_ancestor:
            continue
        project_file = os.path.join(d, ".project")
        try:
            with open(project_file) as f:
                content = f.read()
        except OSError:
            continue
        if AUTO_GEN_NOTICE in content:
            os.remove(project_file)
            for extra in (".classpath",):
                p = os.path.join(d, extra)
                if os.path.isfile(p):
                    os.remove(p)
            settings = os.path.join(d, ".settings")
            if os.path.isdir(settings):
                shutil.rmtree(settings)
            removed.append(d)
        else:
            foreign_conflicts.append(d)

    return removed, foreign_conflicts


def existing_src_dirs(workspace, pkg_path):
    """Return all conventional source/resource directories that exist."""
    found = []
    pkg_abs = os.path.join(workspace, pkg_path)

    for candidate in SRC_DIR_CANDIDATES:
        if os.path.isdir(os.path.join(pkg_abs, candidate)):
            found.append(candidate)

    return found


def _print_timing_summary(run_start):
    """Print a 'where did the time go' table: the slowest individual
    phases/subprocess calls first, plus the grand total wall time."""
    total = time.perf_counter() - run_start

    print("\n" + "=" * 72)
    print("TIMING SUMMARY (slowest first)")
    print("=" * 72)

    if not _TIMINGS:
        print("  (no timed operations recorded)")
    else:
        for label, elapsed in sorted(_TIMINGS, key=lambda t: -t[1])[:25]:
            pct = (elapsed / total * 100) if total else 0
            print(f"  {elapsed:8.2f}s  ({pct:5.1f}%)  {label}")

        # Break subprocess calls out separately since a single "phase"
        # (e.g. resolve maven jars) can be made up of dozens of them --
        # this shows whether the time is one slow bazel call or many
        # small ones (i.e. still-too-many-invocations).
        subproc_time = sum(e for l, e in _TIMINGS if l.startswith(("subprocess:", "cquery")))
        subproc_count = sum(1 for l, e in _TIMINGS if l.startswith(("subprocess:", "cquery")))
        if subproc_count:
            print(
                f"\n  Total: {subproc_count} bazel subprocess call(s) "
                f"took {subproc_time:.2f}s combined "
                f"({subproc_time / total * 100 if total else 0:.1f}% of total)."
            )

    print(f"\n  TOTAL WALL TIME: {total:.2f}s")
    print("=" * 72)


