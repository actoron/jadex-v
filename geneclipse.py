    parser.add_argument("--workspace", default=".", help="Path to the Bazel workspace root (containing MODULE.bazel)")
    parser.add_argument("--jdk", type=int, default=21, help="Fallback JDK version if javacopts don't specify one")
    parser.add_argument("--dry-run", action="store_true", help="Print what would be generated, write nothing")
    parser.add_argument(
        "--skip-non-java-root-project",
        action="store_true",
        help="Do not generate a non-Java Eclipse .project in the workspace root",
    )
    args = parser.parse_args()

    workspace = os.path.abspath(args.workspace)
    if not os.path.isfile(os.path.join(workspace, "MODULE.bazel")):
        raise SystemExit(f"No MODULE.bazel found in {workspace} -- pass --workspace correctly")

    if shutil.which("bazel") is None:
        raise SystemExit("bazel not found on PATH")

    run_start = time.perf_counter()

    with timed("bazel info: execution_root"):
        execroot = bazel_info("execution_root", workspace)

    if not args.dry_run:
        with timed("clean workspace (metadata + bin/ dirs)"):
            clean_workspace(workspace)

    with timed("bazel query: enumerate java_* targets"):
        rules = query_all_java_rules(workspace)
    print(f"  Found {len(rules)} target(s).")

    if not rules:
        raise SystemExit("No matching Java targets found -- nothing to generate")

    with timed("build project models (deps graph + Maven dep collection)"):
        projects = build_project_models(rules, workspace)

    # Eclipse does not support nested projects by default: a project's
    # folder cannot contain another project's folder. If one Bazel
    # package is a filesystem ancestor of another (e.g. a top-level
    # "everything" aggregate java_library at the workspace root, with
    # every other module living in subdirectories underneath it), skip
    # generating a project for the ancestor -- otherwise JDT LS throws a
    # ResourceException on that .project and aborts importing everything.
    all_pkgs = set(projects.keys())
    skipped_ancestors = set()
    for pkg in list(projects.keys()):
        prefix = pkg + "/" if pkg else ""
        if any(other != pkg and other.startswith(prefix) for other in all_pkgs):
            skipped_ancestors.add(pkg)
