            project_name = project_name_for_package(pkg_path)
            pkg_dir = os.path.join(workspace, pkg_path)
            src_dirs = existing_src_dirs(workspace, pkg_path)
            jdk = guess_jdk_version(model["javacopts"], args.jdk)

