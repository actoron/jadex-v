    all_maven_labels = set()
    for model in projects.values():
        all_maven_labels |= model["maven_deps"]

    with timed(f"resolve {len(all_maven_labels)} maven jar(s)"):
        maven_jars = resolve_maven_jars(all_maven_labels, workspace, execroot)

